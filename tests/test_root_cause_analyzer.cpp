TEST_F(RootCauseAnalyzerTest, BuildCausalGraph_CausalEdgeDetected) {
    // A causes B: B is a shifted copy of A (B[i] = A[i-1]).
    // Using non-monotone values so that the instantaneous correlation is < 1
    // while the lagged correlation is exactly 1, triggering edge detection.
    std::vector<double> a_vals = {1, 3, 5, 2, 8, 4, 6, 9, 7};
    std::vector<double> b_vals = {0, 1, 3, 5, 2, 8, 4, 6, 9}; // B lags A by 1

    RootCauseAnalyzerConfig cfg;
    cfg.correlation_threshold = 0.5;
    analyzer_.setConfig(cfg);

    auto ts_a = makeSeriesFromVec("write_amp", a_vals);
    auto ts_b = makeSeriesFromVec("latency",   b_vals);

    auto graph = analyzer_.buildCausalGraph({ts_a, ts_b});

    EXPECT_EQ(graph.nodes.size(), 2u);
    // There should be at least one edge (write_amp → latency)
    bool found_edge = false;
    for (const auto& e : graph.edges) {
        if (e.from_metric == "write_amp" && e.to_metric == "latency") {
            found_edge = true;
        }
    }
    EXPECT_TRUE(found_edge);
}

TEST_F(RootCauseAnalyzerTest, BuildCausalGraph_NoEdge_ForUncorrelatedSeries) {
    // Constant series → no meaningful correlation
    std::vector<double> flat = {3, 3, 3, 3, 3, 3, 3, 3, 3};
    std::vector<double> linear = {1, 2, 3, 4, 5, 6, 7, 8, 9};

    RootCauseAnalyzerConfig cfg;
    cfg.correlation_threshold = 0.9;
    analyzer_.setConfig(cfg);

    auto graph = analyzer_.buildCausalGraph({makeSeriesFromVec("flat", flat),
                                             makeSeriesFromVec("linear", linear)});
    // flat has zero variance → correlation 0 → no edge
    bool flat_edge = false;
    for (const auto& e : graph.edges) {
        if (e.from_metric == "flat" || e.to_metric == "flat") {
            flat_edge = true;
        }
    }
    EXPECT_FALSE(flat_edge);
}

TEST_F(RootCauseAnalyzerTest, BuildCausalGraph_NoEdge_WhenInstantaneousCorrelationDominates) {
    // When the instantaneous correlation is at least as strong as the lagged
    // correlation, no causal edge should be inferred (X and Y are in sync).
    // Both series are identical (perfectly correlated instantaneously);
    // the lag-1 correlation is equally strong, so |r_lag| is NOT strictly
    // greater than |r_inst|, and no edge should be added.
    std::vector<double> x = {1, 4, 2, 8, 5, 7, 3, 9, 6};
    std::vector<double> y = x; // identical → instantaneous r = 1.0

    RootCauseAnalyzerConfig cfg;
    cfg.correlation_threshold = 0.5;
    analyzer_.setConfig(cfg);

    auto graph = analyzer_.buildCausalGraph({makeSeriesFromVec("x", x),
                                             makeSeriesFromVec("y", y)});
    // Instantaneous correlation is 1.0; lag-1 correlation is also high but
    // NOT strictly greater, so no causal edge should appear.
    EXPECT_TRUE(graph.edges.empty());
}

TEST_F(RootCauseAnalyzerTest, BuildCausalGraph_RootNodesFromGraph) {
    std::vector<double> a = {1, 2, 3, 4, 5, 6, 7, 8, 9};
    std::vector<double> b = {0, 1, 2, 3, 4, 5, 6, 7, 8};

    RootCauseAnalyzerConfig cfg;
    cfg.correlation_threshold = 0.5;
    analyzer_.setConfig(cfg);

    auto graph = analyzer_.buildCausalGraph({makeSeriesFromVec("a", a),
                                             makeSeriesFromVec("b", b)});
    auto roots = graph.rootNodes();
    EXPECT_FALSE(roots.empty());
}

TEST_F(RootCauseAnalyzerTest, BuildCausalGraph_EmptyInput_EmptyGraph) {
    auto graph = analyzer_.buildCausalGraph({});
    EXPECT_TRUE(graph.nodes.empty());
    EXPECT_TRUE(graph.edges.empty());
}

