/// Build a simple two-point TimeSeries from a pair of values.
TimeSeries makeSeries(const std::string& name, double first, double last) {
    TimeSeries ts;
    ts.name = name;
    ts.unit = "unit";
    auto now = std::chrono::system_clock::now();
    ts.points.push_back({now - 1s, first});
    ts.points.push_back({now, last});
    return ts;
}

/// Build a longer TimeSeries from a vector of values.
TimeSeries makeSeriesFromVec(const std::string& name,
                             const std::vector<double>& values) {
    TimeSeries ts;
    ts.name = name;
    ts.unit = "unit";
    auto now = std::chrono::system_clock::now();
    for (size_t i = 0; i < values.size(); ++i) {
        ts.points.push_back({now - std::chrono::seconds(values.size() - i), values[i]});
    }
    return ts;
}

/// Build a default SystemSnapshot with sensible "healthy" baseline values.
SystemSnapshot healthySnapshot() {
    SystemSnapshot s;
    s.write_amplification      = 3.2;
    s.read_amplification       = 1.5;
    s.compaction_rate_mb_s     = 10.0;
    s.memtable_flush_rate_mb_s = 5.0;
    s.sstable_count            = 100.0;
    s.block_cache_hit_rate_pct = 85.0;
    s.row_cache_hit_rate_pct   = 70.0;
    s.avg_query_latency_ms     = 5.0;
    s.p99_query_latency_ms     = 20.0;
    s.queries_per_second       = 1000.0;
    s.cpu_usage_pct            = 30.0;
    s.memory_usage_mb          = 2048.0;
    s.disk_io_utilization_pct  = 20.0;
    s.captured_at              = std::chrono::system_clock::now();
    return s;
}

/// Build a PerformanceIssue of the given category and severity.
PerformanceIssue makeIssue(IssueCategory cat, IssueSeverity sev = IssueSeverity::WARNING) {
    PerformanceIssue issue;
    issue.category    = cat;
    issue.severity    = sev;
    issue.title       = "Test issue";
    issue.description = "Generated by test";
    return issue;
}

