TEST_F(RootCauseAnalyzerTest, AddRemoveTimeSeries_RoundTrip) {
    std::vector<double> vals = {1, 2, 3, 4, 5};
    analyzer_.addTimeSeries(makeSeriesFromVec("my_metric", vals));

    // After adding, findCorrelations should treat the metric as known
    auto correlations = analyzer_.findCorrelations("my_metric");
    // No other series → empty, but no throw
    EXPECT_NO_THROW((void)correlations.size());

    analyzer_.removeTimeSeries("my_metric");

    // After removing, the metric is unknown
    correlations = analyzer_.findCorrelations("my_metric");
    EXPECT_TRUE(correlations.empty());
}

TEST_F(RootCauseAnalyzerTest, AddTimeSeries_Replacement_SameNameOverwritten) {
    analyzer_.addTimeSeries(makeSeriesFromVec("m", {1, 2, 3}));
    analyzer_.addTimeSeries(makeSeriesFromVec("m", {4, 5, 6})); // replace
    // No crash, just a replacement
    EXPECT_NO_THROW((void)analyzer_.findCorrelations("m"));
}

