#include "utils/file_utils.h"
#include <fstream>
#include <sstream>
#include <stdexcept>

namespace themis {
namespace utils {

std::string readFileContents(const std::string& path) {
    std::ifstream file(path, std::ios::binary);
    if (!file) {
        throw std::runtime_error("Failed to open file: " + path);
    }
    std::stringstream buffer;
    buffer << file.rdbuf();
    return buffer.str();
}

} // namespace utils
} // namespace themis
