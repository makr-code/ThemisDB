#!/usr/bin/env python3
"""
ThemisDB Test Data Loader
Loads test documents across multiple shards using consistent hashing
"""

import asyncio
import aiohttp
import json
import os
import sys
from datetime import datetime
from faker import Faker
import random
import hashlib

fake = Faker()

class TestDataLoader:
    def __init__(self, shard_endpoints: list, total_documents: int, batch_size: int = 1000):
        self.shard_endpoints = shard_endpoints
        self.total_documents = total_documents
        self.batch_size = batch_size
        self.loaded_count = 0
        
    def log(self, message: str):
        timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        print(f"[{timestamp}] {message}", flush=True)
    
    def hash_to_shard(self, doc_id: str) -> str:
        """Consistent hash to determine target shard"""
        hash_value = int(hashlib.md5(doc_id.encode()).hexdigest(), 16)
        shard_index = hash_value % len(self.shard_endpoints)
        return self.shard_endpoints[shard_index]
    
    def generate_document(self, doc_id: int) -> dict:
        """Generate a realistic test document"""
        categories = ["Genehmigung", "Antrag", "Bescheid", "Gutachten", "Protokoll", 
                     "Verordnung", "Stellungnahme", "Anzeige", "Bericht", "Dokumentation"]
        
        return {
            "id": f"doc_{doc_id:010d}",
            "data": {
                "title": fake.catch_phrase(),
                "author": fake.name(),
                "organization": fake.company(),
                "category": random.choice(categories),
                "created_at": fake.date_time_this_year().isoformat(),
                "modified_at": datetime.now().isoformat(),
                "content": fake.text(max_nb_chars=2000),
                "tags": [fake.word() for _ in range(random.randint(2, 8))],
                "metadata": {
                    "department": fake.job(),
                    "priority": random.choice(["low", "medium", "high", "urgent"]),
                    "status": random.choice(["draft", "review", "approved", "archived"]),
                    "file_size_kb": random.randint(10, 5000),
                    "page_count": random.randint(1, 100),
                    "language": "de",
                    "aktenzeichen": f"AZ-{random.randint(1000, 9999)}/{datetime.now().year}",
                },
                "location": {
                    "city": fake.city(),
                    "zip_code": fake.postcode(),
                    "coordinates": {
                        "lat": float(fake.latitude()),
                        "lon": float(fake.longitude())
                    }
                },
                # Vector embedding placeholder (would be generated by embedding model)
                "embedding": [random.random() for _ in range(768)]
            }
        }
    
    async def load_batch(self, session: aiohttp.ClientSession, documents: list):
        """Load a batch of documents to their respective shards"""
        shard_batches = {}
        
        # Group documents by target shard
        for doc in documents:
            target_shard = self.hash_to_shard(doc["id"])
            if target_shard not in shard_batches:
                shard_batches[target_shard] = []
            shard_batches[target_shard].append(doc)
        
        # Send batch to each shard
        tasks = []
        for shard_endpoint, docs in shard_batches.items():
            task = self.send_to_shard(session, shard_endpoint, docs)
            tasks.append(task)
        
        results = await asyncio.gather(*tasks, return_exceptions=True)
        
        # Count successful loads
        success_count = sum(1 for r in results if isinstance(r, int))
        self.loaded_count += success_count
        
        return success_count
    
    async def send_to_shard(self, session: aiohttp.ClientSession, endpoint: str, documents: list) -> int:
        """Send documents to a single shard using batch API"""
        try:
            url = f"http://{endpoint}/entities/batch"
            payload = {"entities": documents}
            
            async with session.post(url, json=payload, timeout=aiohttp.ClientTimeout(total=60)) as resp:
                if resp.status in [200, 201]:
                    return len(documents)
                else:
                    text = await resp.text()
                    self.log(f"Failed to load batch to {endpoint}: HTTP {resp.status} - {text}")
                    return 0
        except Exception as e:
            self.log(f"Error sending to {endpoint}: {e}")
            return 0
    
    async def load_data(self):
        """Main data loading loop"""
        self.log(f"Starting data load: {self.total_documents:,} documents across {len(self.shard_endpoints)} shards")
        self.log(f"Batch size: {self.batch_size}")
        
        start_time = datetime.now()
        
        connector = aiohttp.TCPConnector(limit=20)
        async with aiohttp.ClientSession(connector=connector) as session:
            batch = []
            
            for i in range(self.total_documents):
                doc = self.generate_document(i)
                batch.append(doc)
                
                if len(batch) >= self.batch_size:
                    await self.load_batch(session, batch)
                    batch = []
                    
                    # Log progress
                    if (i + 1) % 10000 == 0:
                        elapsed = (datetime.now() - start_time).total_seconds()
                        docs_per_sec = self.loaded_count / elapsed if elapsed > 0 else 0
                        eta_seconds = (self.total_documents - self.loaded_count) / docs_per_sec if docs_per_sec > 0 else 0
                        self.log(f"Progress: {self.loaded_count:,}/{self.total_documents:,} ({self.loaded_count/self.total_documents*100:.1f}%) - {docs_per_sec:.0f} docs/sec - ETA: {eta_seconds/60:.0f}m")
            
            # Load remaining documents
            if batch:
                await self.load_batch(session, batch)
        
        end_time = datetime.now()
        duration = (end_time - start_time).total_seconds()
        
        self.log(f"Data loading completed!")
        self.log(f"Total documents loaded: {self.loaded_count:,}")
        self.log(f"Duration: {duration:.1f} seconds ({duration/60:.1f} minutes)")
        self.log(f"Average throughput: {self.loaded_count/duration:.1f} docs/sec")

async def main():
    endpoints_str = os.getenv("SHARD_ENDPOINTS", "shard-0:8765,shard-1:8765,shard-2:8765")
    endpoints = [e.strip() for e in endpoints_str.split(",")]
    
    total_docs = int(os.getenv("DOCUMENTS_TOTAL", "5000000"))
    batch_size = int(os.getenv("BATCH_SIZE", "1000"))
    
    loader = TestDataLoader(endpoints, total_docs, batch_size)
    
    try:
        await loader.load_data()
    except KeyboardInterrupt:
        print("\nData loading interrupted by user")
        sys.exit(1)
    except Exception as e:
        print(f"Data loading failed: {e}")
        import traceback
        traceback.print_exc()
        sys.exit(1)

if __name__ == "__main__":
    asyncio.run(main())
