// ---------------------------------------------------------------------------
// ICorrelationIDProvider — pure-virtual interface for ID generation/extraction
// ---------------------------------------------------------------------------

/**
 * @brief Pure-virtual factory and extractor interface for `CorrelationId` values.
 *
 * ### Contract
 * - `generate()` returns a new, unique `CorrelationId` on every call.
 * - `extract()` parses the `X-Correlation-ID` header from the supplied HTTP
 *   headers map; if the header is absent or malformed, a freshly generated ID
 *   is returned (never fails).
 * - Neither `generate()` nor `extract()` embed PII, IP addresses, or user
 *   identifiers in the returned ID.  The format is opaque UUID only.
 *
 * ### Thread safety
 * Both methods must be safe to call concurrently from multiple threads.
 */
class ICorrelationIDProvider {
public:
    virtual ~ICorrelationIDProvider() = default;

    /// Header name used for inbound and outbound correlation ID propagation.
    static constexpr std::string_view kHeaderName = "X-Correlation-ID";

    /**
     * @brief Generate a new unique `CorrelationId`.
     *
     * Implementations must use a cryptographically strong source of entropy
     * (e.g. `boost::uuids::random_generator`).
     *
     * @return A freshly generated, globally unique `CorrelationId`.
     */
    virtual CorrelationId generate() const = 0;

    /**
     * @brief Extract a `CorrelationId` from HTTP headers.
     *
     * Looks up the `X-Correlation-ID` header in `headers` and parses it.
     * If the header is absent, empty, or cannot be parsed as a UUID, a new
     * ID is generated via `generate()` and returned instead.
     *
     * @param headers  HTTP request headers (case-sensitive map).
     * @return The extracted or freshly generated `CorrelationId`.
     */
    virtual CorrelationId extract(const std::unordered_map<std::string, std::string>& headers) const = 0;

    /**
     * @brief Serialise a `CorrelationId` to the canonical UUID string form
     *        suitable for placing in the `X-Correlation-ID` response header.
     *
     * Equivalent to `id.toString()`.
     */
    static std::string serialize(const CorrelationId& id) { return id.toString(); }
};

